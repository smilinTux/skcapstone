#!/usr/bin/env bash
# Regenerate deploy/fleet-constraints.txt, the fleet's fully resolved lock.
#
#   scripts/fleet-lock.sh            rewrite the lock, keeping every existing pin
#                                    unless an input forces a change
#   scripts/fleet-lock.sh --check    exit 1 if the lock is stale for its inputs
#   scripts/fleet-lock.sh --upgrade-package NAME [...]   move NAME to its newest
#                                    version the inputs allow (what Renovate does)
#
# Inputs: pyproject.toml with the fleet-qualify extra (skcapstone's own runtime),
# deploy/fleet-requirements.in (SK pins) and deploy/fleet-tools.in (third-party
# tools in the same venv). The lock is universal: one file, with environment
# markers, for every fleet Python (3.12 on chiap*, 3.14 on ziowk01).
set -euo pipefail
cd "$(dirname "$0")/.."
LOCK=deploy/fleet-constraints.txt
compile() {
  # skcapstone itself is the local checkout (hosts install '.'), never a PyPI
  # release: SK packages that depend on skcapstone (skdashboard) must resolve
  # against THIS tree's requirements, so it goes in as a path and is left out
  # of the output.
  printf 'skcapstone[fleet-qualify] @ file://%s\n' "$PWD" > "$tmp/self.in"
  uv pip compile --quiet --universal --python-version 3.12 --no-annotate --no-header \
    --no-emit-package skcapstone \
    "$tmp/self.in" deploy/fleet-requirements.in deploy/fleet-tools.in "$@"
}
header() {
  cat <<'HDR'
# GENERATED by scripts/fleet-lock.sh: the fleet runtime's fully resolved lock.
# Do not edit by hand. Change deploy/fleet-requirements.in (SK pins),
# deploy/fleet-tools.in (third-party tools) or pyproject.toml, then rerun the
# script and commit both. Consumers: CI and rollout install with `-c` (this
# file) and `-r deploy/fleet-requirements.in`; the rollout also pins every
# entry a host already has installed, then the parity gate and `pip check`
# must pass before the next host. Gate: .github/workflows/fleet-lock.yml.
HDR
}
upgrade=()
check=0
while [ $# -gt 0 ]; do
  case "$1" in
    --check) check=1 ;;
    --upgrade-package) upgrade+=(--upgrade-package "$2"); shift ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
  shift
done
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
# The current lock seeds the resolver, so unrelated pins never move.
grep -v '^#' "$LOCK" > "$tmp/prev.txt" || true
cp "$tmp/prev.txt" "$tmp/out.txt"
compile -o "$tmp/out.txt" ${upgrade[@]+"${upgrade[@]}"}
{ header; grep -v '^#' "$tmp/out.txt"; } > "$tmp/lock.txt"
if [ "$check" = 1 ]; then
  if ! diff -u "$LOCK" "$tmp/lock.txt"; then
    echo "fleet lock is stale: run scripts/fleet-lock.sh and commit the result" >&2
    exit 1
  fi
  echo "fleet lock is current"
  exit 0
fi
cp "$tmp/lock.txt" "$LOCK"
echo "wrote $LOCK ($(grep -vc '^#' "$LOCK") pins)"
