"""Fleet dependency parity: installed versions must match the fleet lock.

Incident 2026-10-13: a PR used a skcoord symbol that existed in the 0.1.87
installed on every host but not in the 0.1.86 pyproject floor CI resolved to.
CI failed; had the floor instead been above production, production would have
broken while CI passed. The fix is one file naming the production versions,
consumed by CI (``pip -c``), rollout (``pip -c``), and this gate.

Incident 2026-11-15 (#1382): that file held only the SK pins, so a pin set
whose caps pulled click and typer down broke huggingface-hub, a third-party
tool in the same venv, and nothing noticed. ``deploy/fleet-constraints.txt``
is now the fully resolved lock (every transitive version, with environment
markers) generated by ``scripts/fleet-lock.sh`` from
``deploy/fleet-requirements.in`` (the SK pins) and ``deploy/fleet-tools.in``.

Two kinds of entry, two rules:

* a name pinned in the requirements file is REQUIRED: missing or different is
  drift;
* any other lock entry is OPTIONAL: a host need not carry it, but if it is
  installed it must be at the lock's version.

Runnable by path with only the standard library plus ``packaging`` so a
rollout can use the freshly pulled checkout's copy, including during rollback.
Exit 0 on parity, 3 on drift (message starts ``DEPENDENCY_DRIFT``), 2 on a
bad constraints file. ``--write-installed PATH`` writes the lock lines for the
optional entries this host has installed, which the rollout passes to
``pip install -r`` so every installed package moves to the lock, not only the
ones the SK packages happen to pull in.
"""

from __future__ import annotations

import argparse
import sys
from importlib import metadata
from pathlib import Path

from packaging.requirements import InvalidRequirement, Requirement
from packaging.utils import canonicalize_name
from packaging.version import Version

DEPLOY = Path(__file__).resolve().parents[3] / "deploy"
DEFAULT_CONSTRAINTS = DEPLOY / "fleet-constraints.txt"
DEFAULT_REQUIREMENTS = DEPLOY / "fleet-requirements.in"
#: The project itself is installed from the checkout, never from the lock.
SELF = "skcapstone"


def parse_constraints(text: str, env: dict[str, str] | None = None) -> dict[str, Version]:
    """Parse exact pins (``name==version [; marker]``) into ``{name: Version}``.

    A line whose marker does not hold for ``env`` (the running interpreter when
    None) is skipped, so a universal lock that pins one package at two versions
    for two Pythons yields exactly one pin here. Two pins that both apply are an
    error.
    """
    pins: dict[str, Version] = {}
    for number, raw in enumerate(text.splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line or line.startswith("-"):
            continue
        try:
            req = Requirement(line)
        except InvalidRequirement as exc:
            raise ValueError(f"line {number}: {exc}") from exc
        specs = list(req.specifier)
        if len(specs) != 1 or specs[0].operator != "==" or "*" in specs[0].version:
            raise ValueError(f"line {number}: {line!r} is not an exact == pin")
        if req.marker is not None and not req.marker.evaluate(env):
            continue
        name = canonicalize_name(req.name)
        if name in pins:
            raise ValueError(f"line {number}: {name} is pinned twice for this environment")
        pins[name] = Version(specs[0].version)
    return pins


def load_constraints(path: Path = DEFAULT_CONSTRAINTS) -> dict[str, Version]:
    return parse_constraints(Path(path).read_text(encoding="utf-8"))


def load_required(path: Path = DEFAULT_REQUIREMENTS) -> set[str] | None:
    """Names the requirements file pins (required on every host), or None
    when the file does not exist (a revision from before the lock, where every
    constraints entry was required)."""
    try:
        return set(load_constraints(path))
    except FileNotFoundError:
        return None


def installed_version(name: str) -> Version | None:
    try:
        return Version(metadata.version(name))
    except metadata.PackageNotFoundError:
        return None


def find_drift(pins: dict[str, Version], required: set[str] | None = None) -> list[str]:
    """One human line per lock entry this host breaks.

    ``required=None`` keeps the original rule (every pin required).
    """
    drift = []
    for name, want in sorted(pins.items()):
        if name == SELF:
            continue
        have = installed_version(name)
        if have is None and required is not None and name not in required:
            continue
        if have != want:
            drift.append(f"{name}: installed {have or 'MISSING'}, constraints pin {want}")
    return drift


def installed_lock_lines(pins: dict[str, Version]) -> list[str]:
    """``name==version`` for every lock entry already installed on this host."""
    return [
        f"{name}=={want}"
        for name, want in sorted(pins.items())
        if name != SELF and installed_version(name) is not None
    ]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--constraints", type=Path, default=DEFAULT_CONSTRAINTS)
    parser.add_argument(
        "--requirements",
        type=Path,
        default=None,
        help="required pins (default: fleet-requirements.in next to --constraints)",
    )
    parser.add_argument("--write-installed", type=Path, default=None)
    args = parser.parse_args(argv)
    try:
        pins = load_constraints(args.constraints)
        required = load_required(
            args.requirements or args.constraints.with_name("fleet-requirements.in")
        )
    except (OSError, ValueError) as exc:
        print(f"DEPENDENCY_CONSTRAINTS_UNREADABLE: {args.constraints}: {exc}", file=sys.stderr)
        return 2
    if args.write_installed is not None:
        args.write_installed.parent.mkdir(parents=True, exist_ok=True)
        lines = installed_lock_lines(pins)
        args.write_installed.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"wrote {len(lines)} installed lock pins to {args.write_installed}")
        return 0
    drift = find_drift(pins, required)
    if drift:
        print(
            "DEPENDENCY_DRIFT: installed environment differs from "
            f"{args.constraints}: " + "; ".join(drift),
            file=sys.stderr,
        )
        return 3
    checked = sorted(required) if required is not None else sorted(pins)
    print(
        f"dependency parity ok: {len(pins)} lock entries, required "
        + ", ".join(f"{n}=={pins[n]}" for n in checked if n in pins)
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
